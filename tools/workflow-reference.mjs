function header(names) {
  return [
    '# Built-in workflow reference',
    '',
    '<!-- Generated by `make reference` from plugins/maister/skills/workflow-engine/workflows/*.yml. Do not edit by hand. -->',
    '',
    'For people who write an overlay of a built-in workflow, or a workflow of their own that starts one. It lists, for each built-in, the inputs it takes, every step and checkpoint in the order a run meets them, what each checkpoint can answer and what each step declares it produces.',
    '',
    'The ids in these tables are what an overlay names: `needs` and `before` of a step you add, `disable` and `tune` of a step that is there. A **checkpoint** is a gate the run stops at for your answer. **Runs when** is the step\'s guard: a step whose guard is false is skipped, and a skipped step still lets the steps after it run. A guard reads an input (`${inputs.<name>}`) or a value an earlier step or checkpoint recorded (`${<id>.values.<name>}`). [Extending Maister](extending.md) explains overlays and the grammar; `/maister:workflow-author nodes <workflow>` lists what an overlay can attach to in your own project.',
    '',
    names.map((n) => `- [\`${n}\`](#${n})`).join('\n'),
    '',
  ].join('\n');
}

function section(name, doc, graph) {
  const titles = doc.display?.titles ?? {};
  const isGate = (node) => node.type === 'gate';
  const lines = [`## ${name}`, '', clean(doc.description ?? ''), ''];
  lines.push(`Started with \`/maister:${name}\`. Definition: \`plugins/maister/skills/workflow-engine/workflows/${name}.yml\`.`, '');

  lines.push('### Inputs', '');
  const inputs = Object.entries(doc.inputs ?? {});
  if (inputs.length === 0) {
    lines.push('None.', '');
  } else {
    lines.push('| Input | Type | Required | Default |', '|---|---|---|---|');
    for (const [id, spec] of inputs) {
      lines.push(row([code(id), spec?.type ?? '', spec?.required ? 'yes' : 'no', 'default' in (spec ?? {}) ? code(String(spec.default)) : '']));
    }
    lines.push('');
  }

  lines.push('### Steps and checkpoints', '');
  lines.push('| # | Id | Title | Kind | Runs | Needs | Runs when |', '|---|---|---|---|---|---|---|');
  graph.nodes.forEach((node, i) => {
    lines.push(row([
      String(i + 1),
      code(node.id),
      titles[node.id] ?? '',
      isGate(node) ? 'checkpoint' : 'step',
      isGate(node) ? '' : code(node.uses ?? ''),
      (node.needs ?? []).map(code).join(', '),
      node.when ? code(node.when) : 'always',
    ]));
  });
  lines.push('');

  const gates = graph.nodes.filter(isGate);
  if (gates.length) {
    lines.push('### Checkpoint answers', '');
    for (const gate of gates) {
      lines.push(`**${code(gate.id)}** asks: ${gate.ask ? `"${clean(gate.ask)}"` : '(no question text)'}`, '');
      for (const [option, spec] of Object.entries(gate.options ?? {})) {
        lines.push(`- ${code(option)}: ${effect(spec)}`);
      }
      lines.push('');
    }
  }

  const producing = graph.nodes.filter((n) => !isGate(n) && n.outputs && (n.outputs.artifacts || n.outputs.values));
  if (producing.length) {
    lines.push('### What each step declares', '');
    lines.push('Artifact paths are relative to the run\'s task directory.', '');
    lines.push('| Step | Artifacts | Values |', '|---|---|---|');
    for (const node of producing) {
      const artifacts = Object.entries(node.outputs.artifacts ?? {}).map(([k, v]) => `${code(k)}: ${code(v)}`).join('<br>');
      const values = Object.entries(node.outputs.values ?? {}).map(([k, v]) => `${code(k)} (${valueType(v)})`).join('<br>');
      lines.push(row([code(node.id), artifacts, values]));
    }
    lines.push('');
  }

  if (doc.outputs && (doc.outputs.artifacts || doc.outputs.values)) {
    lines.push('### What a run hands back', '');
    lines.push('What a parent run, or a workflow that starts this one, can read once it ends.', '');
    lines.push('| Output | Kind | From |', '|---|---|---|');
    for (const [k, v] of Object.entries(doc.outputs.artifacts ?? {})) lines.push(row([code(k), 'artifact', code(v)]));
    for (const [k, v] of Object.entries(doc.outputs.values ?? {})) lines.push(row([code(k), 'value', code(v)]));
    lines.push('');
  }
  return lines.join('\n');
}

function effect(spec) {
  const s = typeof spec === 'string' ? { effect: spec } : (spec ?? {});
  const parts = [];
  if (s.effect === 'continue') parts.push('continue');
  else if (s.effect === 'revise') parts.push(`revise: sends the run back to ${code(s.reruns ?? '?')}`);
  else if (s.effect === 'stop') parts.push('stop: ends the run');
  else parts.push(String(s.effect ?? ''));
  if (s.sets) parts.push(`sets ${Object.entries(s.sets).map(([k, v]) => code(`${k}: ${v}`)).join(', ')}`);
  if (s.grants) parts.push(`grants ${s.grants.map(code).join(', ')}`);
  return parts.join('; ');
}

function valueType(v) {
  if (typeof v === 'string') return v;
  if (v && Array.isArray(v.enum)) return `one of ${v.enum.join(', ')}`;
  if (v && v.type) return v.type;
  return JSON.stringify(v);
}

/** A table cell is one line, and a literal pipe would end it. */
function row(cells) {
  return `| ${cells.map((c) => String(c).replace(/\n/g, ' ').replace(/\|/g, '\\|')).join(' | ')} |`;
}

function code(text) {
  return `\`${text}\``;
}

function clean(text) {
  return String(text).replace(/\s+/g, ' ').trim();
}

function rel(file) {
  return path.relative(REPO, file);
}

function fail(message) {
  process.stderr.write(`workflow-reference: ${message}\n`);
  process.exit(1);
}

function parseFlags(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') flags.check = true;
    else if (arg === '--out') flags.out = argv[++i];
    else fail(`unknown argument "${arg}"`);
  }
  return flags;
}

await main(process.argv.slice(2));
