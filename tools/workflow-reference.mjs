/**
 * The built-in workflow reference: one generated page describing every
 * built-in definition, written to `docs/workflow-reference.md`.
 *
 *   node tools/workflow-reference.mjs [--out <file>] [--check]
 *
 * Why this exists. An overlay author needs each built-in's node ids, which of
 * them are gates, the guards that skip them, the inputs the workflow takes and
 * the outputs a node declares. A hand-kept table drifts the first time a
 * definition changes, so every row here is read from the definitions:
 *
 * - the graph comes from the engine's own `resolve` verb, run on each
 *   `skills/workflow-engine/workflows/*.yml`, so the nodes are listed in the
 *   frozen order a run uses and no second parser guesses at the grammar;
 * - the description, inputs, workflow outputs and node titles come from the
 *   definition file itself, read with the engine's definition reader.
 *
 * `--check` writes nothing and exits 1 when the file on disk is not what this
 * would write. Development tooling: it ships with nothing and changes nothing
 * but its one output file. Zero dependencies, Node >= 20.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENGINE = path.join(REPO, 'plugins/maister/skills/workflow-engine');
const WORKFLOWS = path.join(ENGINE, 'workflows');
const DEFAULT_OUT = path.join(REPO, 'docs/workflow-reference.md');

/** The order a reader meets the built-ins in; a definition not named here follows, by name. */
const ORDER = ['development', 'research', 'performance', 'migration', 'product-design', 'mockup-studio'];

async function main(argv) {
  const flags = parseFlags(argv);
  const out = flags.out ? path.resolve(flags.out) : DEFAULT_OUT;
  const { readDefinition } = await import(pathToFileURL(path.join(ENGINE, 'scripts/lib/definition.mjs')).href);

  const files = fs.readdirSync(WORKFLOWS).filter((f) => f.endsWith('.yml'));
  const names = files.map((f) => f.slice(0, -4)).sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  const sections = names.map((name) => {
    const file = path.join(WORKFLOWS, `${name}.yml`);
    const read = readDefinition(file);
    if (!read.doc) fail(`${rel(file)} cannot be read: ${read.errors.map((e) => e.message).join('; ')}`);
    return section(name, read.doc, resolved(file));
  });
  const page = [header(names), ...sections].join('\n');

  if (flags.check) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (current !== page) {
      process.stderr.write(`${rel(out)} is stale — run make reference\n`);
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(out, page);
  process.stdout.write(`${rel(out)}\n`);
}

function rank(name) {
  const at = ORDER.indexOf(name);
  return at === -1 ? ORDER.length : at;
}

/** The folded graph, exactly as the engine's `resolve` verb prints it. */
function resolved(file) {
  let stdout;
  try {
    stdout = execFileSync(process.execPath, [path.join(ENGINE, 'scripts/workflow.mjs'), 'resolve', '--definition', file], {
      encoding: 'utf8',
      env: { ...process.env, MAISTER_NO_OPEN: '1' },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (err) {
    fail(`the engine could not resolve ${rel(file)}: ${(err.stderr || err.message).toString().trim()}`);
  }
  const graph = JSON.parse(stdout);
  if (!graph.ok) fail(`${rel(file)} does not validate: ${JSON.stringify(graph.errors)}`);
  return graph;
}

