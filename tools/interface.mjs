/** `description` with its version worked out against `baseline`, the file it replaces. */
export function versioned(description, baseline) {
  const previous = isMap(baseline) ? baseline : null;
  const [major, minor] = parseVersion(previous?.interface_version);
  let version = '1.0';
  if (previous) {
    const change = compare(entries(withoutVersion(previous)), entries(description));
    // A state entry removed or changed is a change of the state shape, which
    // the writer's own schema version must say too.
    const stateBroken = change.broken.filter(each => each.startsWith('state.') && !each.startsWith('state.schema_version'));
    if (stateBroken.length && previous.state?.schema_version === description.state.schema_version) {
      throw new Error(`the state shape changed (${stateBroken.join(', ')}) while STATE_SCHEMA_VERSION stayed ${description.state.schema_version}; raise it in lib/state.mjs`);
    }
    if (change.broken.length) version = `${major + 1}.0`;
    else if (change.added.length) version = `${major}.${minor + 1}`;
    else version = `${major}.${minor}`;
  }
  return sorted({ interface_version: version, generated: GENERATED, ...description });
}

function parseVersion(value) {
  const match = typeof value === 'string' ? value.match(/^(\d+)\.(\d+)$/) : null;
  return match ? [Number(match[1]), Number(match[2])] : [1, 0];
}

function withoutVersion(document) {
  const { interface_version: _version, generated: _generated, ...rest } = document;
  return rest;
}

/**
 * The description as entries a change is judged on: every scalar as
 * `path=value`, every list member as `path[member]`. A path present before and
 * gone now, or holding another value, is a breaking change; a new one adds.
 */
function entries(value, prefix = '', out = new Map()) {
  if (Array.isArray(value)) {
    for (const member of value) {
      if (isMap(member) || Array.isArray(member)) entries(member, `${prefix}[]`, out);
      else out.set(`${prefix}[${member}]`, true);
    }
  } else if (isMap(value)) {
    for (const [key, field] of Object.entries(value)) entries(field, prefix ? `${prefix}.${key}` : key, out);
  } else out.set(prefix, value);
  return out;
}

function compare(before, after) {
  const broken = [];
  const added = [];
  for (const [key, value] of before) {
    if (!after.has(key) || after.get(key) !== value) broken.push(key);
  }
  for (const key of after.keys()) if (!before.has(key)) added.push(key);
  return { broken, added };
}

// Node resolves symlinks in the main module's URL but not in argv[1], so the
// invoked path is resolved the same way before comparing; run through a
// symlinked directory (macOS /tmp is one) the script would otherwise do nothing.
function invokedPath(arg) {
  try {
    return fs.realpathSync(arg);
  } catch {
    return path.resolve(arg);
  }
}

