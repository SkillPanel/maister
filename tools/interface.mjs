/** A refusal code's spelling: lower-case words joined by hyphens, two at least. */
const CODE = '[a-z][a-z0-9]*(?:-[a-z0-9]+)+';

/**
 * The refusal codes each verb can raise: every function reachable from the
 * verb's handler in `workflow.mjs` — through same-file references, imports,
 * namespace members and the handler's own module loads — and every code raised
 * in one of them, in the forms the engine raises them:
 *
 * - `refuse('code', …)`, `refused…('code', …)`, `new Refusal('code', …)`, or
 *   the same with a constant (`refuse(NAME)`, `refuse(NAME.key)`);
 * - an `errors: [{ code: 'code' | NAME.key, … }]` result;
 * - `codes: NAME`, a write primitive's code table;
 * - `code: NAME.key`, where `NAME` is a module's refusal table;
 * - in `workflow.mjs`, a `code: …` line written to stderr, or a constant
 *   holding one;
 * - a code spelled after the verb, `refuse(`${verb}-not-running`)`, as the
 *   verb being walked spells it.
 *
 * Two places stop the walk, because what is raised there never reaches the
 * verb's caller as a refusal: the body of a `try` whose `catch` neither throws
 * nor returns errors (a projection written after the state landed, kept as a
 * warning), and a call into another verb's entry whose result the caller does
 * not pass on (the state writer reading a gate's labels from `gateBrief`).
 * Elsewhere it over-reaches rather than under-reaches: a function is reached
 * when its name is mentioned in reachable code, comments and strings aside.
 */
export function refusalsByVerb(scriptsDir, verbs, runners) {
  const modules = new Map();
  const moduleOf = file => {
    if (!modules.has(file)) modules.set(file, fs.existsSync(file) ? parseModule(file) : null);
    return modules.get(file);
  };
  const entry = path.join(scriptsDir, 'workflow.mjs');
  const lib = path.join(scriptsDir, 'lib');
  const handlerTargets = verb => {
    const module = moduleOf(entry);
    const chunk = module?.chunks.get(runners[verb]);
    return chunk ? referencesOf(module, chunk, lib, verbs).filter(each => each.loaded) : [];
  };
  const entries = new Map(Object.keys(verbs).map(verb => [verb, new Set(handlerTargets(verb).map(each => `${each.file}#${each.name}`))]));

  const result = {};
  for (const verb of Object.keys(verbs)) {
    const others = new Set([...entries].filter(([other]) => other !== verb).flatMap(([, set]) => [...set]));
    for (const own of entries.get(verb)) others.delete(own);
    const codes = new Set();
    const seen = new Set();
    const queue = [[entry, runners[verb]]];
    while (queue.length) {
      const [file, name] = queue.shift();
      const key = `${file}#${name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const module = moduleOf(file);
      const chunk = module?.chunks.get(name);
      if (!chunk) continue;
      const swallowed = swallowingTries(module, chunk);
      const live = at => !swallowed.some(([from, to]) => at >= from && at < to);
      for (const { code, suffix, at } of codesIn(module, chunk, file === entry)) if (live(at)) codes.add(code ?? `${verb}${suffix}`);
      for (const target of referencesOf(module, chunk, lib, verbs)) {
        if (!live(target.at)) continue;
        const targetKey = `${target.file}#${target.name}`;
        if (others.has(targetKey) && !passesOn(module, chunk, target.local)) continue;
        queue.push([target.file, target.name]);
      }
    }
    result[verb] = [...codes].sort();
  }
  return result;
}

/**
 * The stretches of a chunk, as offsets into it, that sit in a `try` whose
 * `catch` neither throws nor returns errors: whatever is raised there is
 * caught and kept, never reported.
 */
function swallowingTries(module, chunk) {
  const code = module.code.slice(chunk.start, chunk.end);
  const original = module.source.slice(chunk.start, chunk.end);
  const ranges = [];
  for (const match of code.matchAll(/\btry\s*\{/g)) {
    const tryEnd = closing(code, match.index + match[0].length - 1);
    if (tryEnd === -1) continue;
    const rest = code.slice(tryEnd + 1).match(/^\s*catch\s*(?:\([^)]*\))?\s*\{/);
    if (!rest) continue;
    const catchOpen = tryEnd + 1 + rest[0].length - 1;
    const catchEnd = closing(code, catchOpen);
    if (catchEnd === -1) continue;
    if (!/\bthrow\b|\berrors\b/.test(original.slice(catchOpen, catchEnd))) ranges.push([match.index, tryEnd + 1]);
  }
  return ranges;
}

/** The offset of the brace closing the one at `open`, in code with strings and comments blanked. */
function closing(code, open) {
  let depth = 0;
  for (let i = open; i < code.length; i += 1) {
    if (code[i] === '{') depth += 1;
    else if (code[i] === '}') {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
}

/** Whether a chunk passes on what its call to `local` returns: returns it, spreads it, or reads its errors. */
function passesOn(module, chunk, local) {
  if (!local) return true;
  const text = module.source.slice(chunk.start, chunk.end);
  const name = local.replace(/[$]/g, '\\$');
  if (new RegExp(`return\\s+(?:await\\s+)?${name}\\(`).test(text)) return true;
  for (const [, variable] of text.matchAll(new RegExp(`(?:const|let|var)?\\s*([\\w$]+)\\s*=\\s*(?:await\\s+)?${name}\\(`, 'g'))) {
    if (new RegExp(`return\\s+${variable}\\b|\\.\\.\\.${variable}\\b|\\b${variable}\\.errors\\b`).test(text)) return true;
  }
  return false;
}

/** A module read for the scan: its top-level chunks by name, and its imports by local name. */
function parseModule(file) {
  const source = fs.readFileSync(file, 'utf8');
  const code = blanked(source);
  const lines = source.split('\n');
  const codeLines = code.split('\n');
  const chunks = new Map();
  let current = null;
  let offset = 0;
  const open = (name, start) => {
    current = { name, start, end: start };
    if (name !== null && !chunks.has(name)) chunks.set(name, current);
  };
  for (let i = 0; i < lines.length; i += 1) {
    const line = codeLines[i];
    if (/^[^\s})\]]/.test(line)) {
      const declared = line.match(/^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function\s*\*?\s*|class\s+|(?:const|let|var)\s+)([A-Za-z_$][\w$]*)/);
      open(declared ? declared[1] : null, offset);
      // `const { a, b } = ns;` makes `a` and `b` names of their own.
      const destructured = line.match(/^(?:const|let|var)\s*\{([^}]*)\}\s*=\s*([A-Za-z_$][\w$]*)/);
      if (destructured) {
        for (const each of destructured[1].split(',').map(part => part.trim()).filter(Boolean)) {
          const [from, as = from] = each.split(/\s*:\s*/);
          chunks.set(as, { name: as, start: offset, end: offset + line.length, alias: { namespace: destructured[2], name: from } });
        }
      }
    }
    offset += line.length + 1;
    if (current) current.end = offset;
  }

  const imports = new Map();
  for (const match of source.matchAll(/^import\s+([\s\S]*?)\s+from\s+'([^']+)';/gm)) {
    const from = path.resolve(path.dirname(file), match[2]);
    if (!match[2].startsWith('.')) continue;
    const clause = match[1];
    const namespace = clause.match(/\*\s+as\s+([A-Za-z_$][\w$]*)/);
    if (namespace) imports.set(namespace[1], { file: from, name: '*' });
    const named = clause.match(/\{([\s\S]*)\}/);
    if (named) {
      for (const each of named[1].split(',').map(part => part.trim()).filter(Boolean)) {
        const [name, as = name] = each.split(/\s+as\s+/);
        imports.set(as, { file: from, name });
      }
    }
  }
  return { file, source, code, chunks, imports };
}

/**
 * Where a chunk's code leads: `{file, name, at, local, loaded}` for each other
 * chunk, here or in an imported module, that it names — `at` its offset in the
 * chunk, `local` the name it is called by here, `loaded` when a handler reached
 * it through a module it loaded by name.
 */
function referencesOf(module, chunk, lib, verbs) {
  const targets = [];
  const text = module.code.slice(chunk.start, chunk.end);
  if (chunk.alias) {
    const target = module.imports.get(chunk.alias.namespace);
    if (target) targets.push({ file: target.file, name: chunk.alias.name, at: 0, local: null });
    return targets;
  }
  for (const match of text.matchAll(/(?<![\w$.])([A-Za-z_$][\w$]*)(?:\s*\.\s*([A-Za-z_$][\w$]*))?/g)) {
    const [, name, member] = match;
    if (name === chunk.name) continue;
    const imported = module.imports.get(name);
    if (imported) {
      if (imported.name === '*') {
        if (member) targets.push({ file: imported.file, name: member, at: match.index, local: null });
      } else targets.push({ file: imported.file, name: imported.name, at: match.index, local: name });
    } else if (module.chunks.has(name)) targets.push({ file: module.file, name, at: match.index, local: name });
  }
  // The handlers load a module by its VERBS entry or its file name, and call
  // into it by name: through `entryOf(<module>, 'fn', …)` or `<module>.fn(…)`.
  const original = module.source.slice(chunk.start, chunk.end);
  const fileOf = (verb, literal) => {
    if (literal) return path.join(lib, literal);
    return verbs[verb] ? path.join(lib, verbs[verb].module) : null;
  };
  const load = String.raw`await\s+loadModule\(\s*(?:VERBS(?:\[\s*'([\w-]+)'\s*\]|\.([\w$]+))\.module|'([\w.-]+)')\s*\)`;
  const loaded = new Map();
  for (const match of original.matchAll(new RegExp(String.raw`(?:const|let)\s+([\w$]+)\s*=\s*${load}`, 'g'))) {
    const file = fileOf(match[2] ?? match[3], match[4]);
    if (file) loaded.set(match[1], file);
  }
  for (const match of original.matchAll(new RegExp(String.raw`entryOf\(\s*(?:([\w$]+)|${load})\s*,\s*'([\w$]+)'`, 'g'))) {
    const file = match[1] ? loaded.get(match[1]) : fileOf(match[2] ?? match[3], match[4]);
    if (file) targets.push({ file, name: match[5], at: match.index, local: null, loaded: true });
  }
  for (const [variable, file] of loaded) {
    for (const match of original.matchAll(new RegExp(String.raw`(?<![\w$.])${variable}\.([\w$]+)\s*\(`, 'g'))) {
      targets.push({ file, name: match[1], at: match.index, local: null, loaded: true });
    }
  }
  return targets;
}

/** The refusal codes a chunk raises, constants resolved: `{code, at}`, `at` the offset in the chunk. */
function codesIn(module, chunk, isEntry) {
  const text = module.source.slice(chunk.start, chunk.end);
  const found = [];
  const shaped = new RegExp(`^${CODE}$`);
  const add = (codes, at) => { for (const code of codes) if (code && shaped.test(code)) found.push({ code, at }); };
  const raise = String.raw`(?:\brefuse[\w$]*|\brefused[\w$]*|\bRefusal)\(\s*`;
  for (const match of text.matchAll(new RegExp(`${raise}'(${CODE})'`, 'g'))) add([match[1]], match.index);
  // A code spelled after the verb that raises it, `${verb}-not-running`.
  for (const match of text.matchAll(new RegExp(String.raw`${raise}${'`'}\$\{[\w$]+\}((?:-[a-z0-9]+)+)${'`'}`, 'g'))) {
    found.push({ suffix: match[1], at: match.index });
  }
  for (const match of text.matchAll(new RegExp(String.raw`${raise}([A-Z][A-Z0-9_]*)(?:\.([\w$]+))?`, 'g'))) {
    add(constantCodes(module, match[1], match[2]), match.index);
  }
  for (const match of text.matchAll(new RegExp(String.raw`errors:\s*\[\s*\{\s*code:\s*'(${CODE})'`, 'g'))) add([match[1]], match.index);
  for (const match of text.matchAll(/errors:\s*\[\s*\{\s*code:\s*([A-Z][A-Z0-9_]*)\.([\w$]+)/g)) {
    add(constantCodes(module, match[1], match[2]), match.index);
  }
  for (const match of text.matchAll(/\bcodes:\s*([A-Z][A-Z0-9_]*)\b/g)) add(constantCodes(module, match[1]), match.index);
  for (const match of text.matchAll(/\bcode:\s*([A-Z][A-Z0-9_]*REFUSAL[A-Z0-9_]*)\.([\w$]+)/g)) {
    add(constantCodes(module, match[1], match[2]), match.index);
  }
  if (isEntry) {
    for (const match of text.matchAll(new RegExp(String.raw`stderr\.write\(\s*[${'`'}'](${CODE}): `, 'g'))) add([match[1]], match.index);
    for (const match of text.matchAll(new RegExp(`^const [A-Z][A-Z0-9_]* = '(${CODE}): `, 'gm'))) add([match[1]], match.index);
  }
  return found;
}

/**
 * The codes the constant `name` holds — its `key` alone when one is named —
 * in this module or the one it is imported from: a string (or the code a
 * `code: message` string opens with), or an object's code-shaped values.
 */
function constantCodes(module, name, key = undefined, depth = 0) {
  if (depth > 3) return [];
  const imported = module.imports.get(name);
  if (imported && imported.name !== '*') {
    const other = fs.existsSync(imported.file) ? parseModule(imported.file) : null;
    return other ? constantCodes(other, imported.name, key, depth + 1) : [];
  }
  const chunk = module.chunks.get(name);
  if (!chunk) return [];
  const text = module.source.slice(chunk.start, chunk.end);
  const body = text.slice(text.indexOf('=') + 1);
  if (key !== undefined) {
    const entry = body.match(new RegExp(`\\b${key}\\s*:\\s*(?:'(${CODE})'|([A-Z][A-Z0-9_]*)\\.([\\w$]+))`));
    if (!entry) return [];
    return entry[1] ? [entry[1]] : constantCodes(module, entry[2], entry[3], depth + 1);
  }
  const string = body.match(new RegExp(`^\\s*'(${CODE})(?::|')`));
  if (string) return [string[1]];
  const codes = [...body.matchAll(new RegExp(`:\\s*'(${CODE})'`, 'g'))].map(each => each[1]);
  for (const [, other, otherKey] of body.matchAll(/:\s*([A-Z][A-Z0-9_]*)\.([\w$]+)/g)) codes.push(...constantCodes(module, other, otherKey, depth + 1));
  return codes;
}

/**
 * `source` with every comment and the inside of every string, template text
 * and regular expression blanked to spaces — lengths and line breaks kept —
 * so a name that only a comment or a message mentions reaches nothing.
 * A template's `${…}` stays code.
 */
function blanked(source) {
  const out = source.split('');
  const blank = (from, to) => { for (let i = from; i < to; i += 1) if (out[i] !== '\n') out[i] = ' '; };
  const templates = [];
  let braces = 0;
  let last = '';
  let i = 0;
  while (i < source.length) {
    const c = source[i];
    const next = source[i + 1];
    if (templates.length && braces === templates.at(-1) && c === '}') {
      templates.pop();
      braces -= 1;
      i = template(i + 1);
      last = '`';
      continue;
    }
    if (c === '/' && next === '/') {
      const end = source.indexOf('\n', i);
      const stop = end === -1 ? source.length : end;
      blank(i, stop);
      i = stop;
      continue;
    }
    if (c === '/' && next === '*') {
      const end = source.indexOf('*/', i + 2);
      const stop = end === -1 ? source.length : end + 2;
      blank(i, stop);
      i = stop;
      continue;
    }
    if (c === '\'' || c === '"') {
      let j = i + 1;
      while (j < source.length && source[j] !== c && source[j] !== '\n') j += source[j] === '\\' ? 2 : 1;
      blank(i + 1, j);
      i = j + 1;
      last = c;
      continue;
    }
    if (c === '`') {
      i = template(i + 1);
      last = '`';
      continue;
    }
    if (c === '/' && regexAllowed(last)) {
      let j = i + 1;
      let inClass = false;
      while (j < source.length && source[j] !== '\n') {
        if (source[j] === '\\') { j += 2; continue; }
        if (source[j] === '[') inClass = true;
        else if (source[j] === ']') inClass = false;
        else if (source[j] === '/' && !inClass) break;
        j += 1;
      }
      blank(i + 1, j);
      i = j + 1;
      last = '/';
      continue;
    }
    if (c === '{') braces += 1;
    if (c === '}') braces -= 1;
    if (!/\s/.test(c)) last = /[\w$]/.test(c) ? wordEnding(source, i) : c;
    i += 1;
  }
  return out.join('');

  // Blank a template's text from `start` up to its closing backtick or its next `${`.
  function template(start) {
    let j = start;
    while (j < source.length) {
      if (source[j] === '\\') { j += 2; continue; }
      if (source[j] === '`') { blank(start, j); return j + 1; }
      if (source[j] === '$' && source[j + 1] === '{') {
        blank(start, j);
        braces += 1;
        templates.push(braces);
        return j + 2;
      }
      j += 1;
    }
    blank(start, j);
    return j;
  }
}

/** The word a run of identifier characters ending at `i` spells, for telling a regex from a division. */
function wordEnding(source, i) {
  let j = i;
  while (j + 1 < source.length && /[\w$]/.test(source[j + 1])) j += 1;
  let k = i;
  while (k > 0 && /[\w$]/.test(source[k - 1])) k -= 1;
  return source.slice(k, j + 1);
}

/** Whether a `/` after `last` opens a regular expression rather than dividing. */
function regexAllowed(last) {
  if (last === '' || /^[(,=:[!&|?{};+\-*%<>~^]$/.test(last)) return true;
  return ['return', 'typeof', 'case', 'in', 'of', 'new', 'delete', 'void', 'throw', 'else', 'do', 'yield', 'await'].includes(last);
}

