/**
 * `VERBS` (verb → module and flags) and `RUNNERS` (verb → handler), read from
 * `workflow.mjs` as written. Strict: a line in either table this cannot read,
 * or a verb in one and not the other, stops the build rather than leaving a
 * verb out of the file.
 */
export function verbTable(source) {
  const block = name => {
    const match = source.match(new RegExp(`^const ${name} = \\{\\n([\\s\\S]*?)^\\};`, 'm'));
    if (!match) throw new Error(`workflow.mjs: no ${name} table`);
    return match[1].split('\n').filter(line => line.trim() !== '' && !line.trim().startsWith('//'));
  };
  const verbs = {};
  for (const line of block('VERBS')) {
    const match = line.match(/^\s*'?([a-z][a-z-]*)'?:\s*\{\s*module:\s*'([^']+)',\s*flags:\s*\[([^\]]*)\]\s*\},?\s*$/);
    if (!match) throw new Error(`workflow.mjs: cannot read this VERBS line: ${line.trim()}`);
    const flags = [...match[3].matchAll(/'([^']+)'/g)].map(each => each[1]);
    verbs[match[1]] = { module: match[2], flags: flags.sort() };
  }
  const runners = {};
  for (const line of block('RUNNERS')) {
    const match = line.match(/^\s*'?([a-z][a-z-]*)'?:\s*([A-Za-z_$][\w$]*),?\s*$/);
    if (!match) throw new Error(`workflow.mjs: cannot read this RUNNERS line: ${line.trim()}`);
    runners[match[1]] = match[2];
  }
  const missing = [...Object.keys(verbs).filter(verb => !runners[verb]), ...Object.keys(runners).filter(verb => !verbs[verb])];
  if (missing.length) throw new Error(`workflow.mjs: VERBS and RUNNERS disagree on ${missing.join(', ')}`);
  return { verbs, runners };
}

