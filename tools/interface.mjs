/**
 * The interface file: one generated description of a plugin tree's public
 * interface, written to `<root>/interface.json`.
 *
 *   node tools/interface.mjs --root <plugin dir> [--baseline <file>] [--check]
 *
 * Why this exists. A consumer pins a commit of the plugin and needs to know,
 * mechanically, what changed between two pins: which keys a gate request may
 * carry and their shapes, which verbs and refusals the engine has, which names
 * it registers. A hand-kept list drifts the first time nobody remembers it, so
 * every section here is read from the code that defines it:
 *
 * - `gate_request` and `checkpoint`: the declared shapes the builders are held
 *   to (`lib/interface-shapes.mjs`), and the subject kinds (`lib/gate-subject.mjs`);
 * - `state`: the writer's own vocabulary and schema version (`lib/state.mjs`);
 * - `engine.verbs`: the verb table in `workflow.mjs`, each verb's flags as it
 *   declares them, and its refusals found by following the verb's handler
 *   through every function it can reach (`refusalsByVerb`);
 * - `agents`, `skills`, `commands`: the directories; `hooks`: `hooks/hooks.json`;
 *   `mcp`: the servers the manifest ships and the tool names shipped files name.
 *
 * The version. `interface_version` is `MAJOR.MINOR`, worked out against the
 * file it replaces (`--baseline`, by default the file on disk): nothing changed
 * keeps it; only additions raise the minor; a removal, or a changed type,
 * required flag or value, raises the major. A state entry removed or changed
 * while `STATE_SCHEMA_VERSION` stayed put is refused, with what to raise.
 *
 * `--check` writes nothing and exits 1 when the file on disk is not what this
 * would write. Development tooling: it ships with nothing, and reads a plugin
 * tree without changing anything but that one file. Zero dependencies, Node >= 20.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const FILE = 'interface.json';
const ENGINE = 'skills/workflow-engine/scripts';

/** What the file says about itself, for a reader who opens it cold. */
const GENERATED = 'Generated by make build from this plugin\'s code; never edited by hand. '
  + 'interface_version is MAJOR.MINOR: a minor step only adds (a key, a verb, a refusal, a name, a value); '
  + 'a major step removes something, or changes a type, a required flag or a value.';

// ---------------------------------------------------------------------------
// entry point
// ---------------------------------------------------------------------------

async function main(argv) {
  const flags = parseFlags(argv);
  const root = path.resolve(flags.root);
  const target = path.join(root, FILE);
  const baselineFile = flags.baseline ? path.resolve(flags.baseline) : target;
  const baseline = readJson(baselineFile);
  const description = await describe(root);
  const document = versioned(description, baseline);
  const text = `${JSON.stringify(document, null, 2)}\n`;
  if (flags.check) {
    const onDisk = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (onDisk === text) return 0;
    process.stderr.write(`interface: ${path.relative(process.cwd(), target) || target} differs from a fresh build — run make build and commit the result\n`);
    return 1;
  }
  fs.writeFileSync(target, text);
  process.stdout.write(`${path.relative(process.cwd(), target) || target} ${document.interface_version}\n`);
  return 0;
}

function parseFlags(argv) {
  const flags = { root: null, baseline: null, check: false };
  for (let i = 0; i < argv.length; i += 1) {
    const [name, inline] = argv[i].split(/=(.*)/s);
    const value = () => (inline !== undefined ? inline : argv[++i]);
    if (name === '--root') flags.root = value();
    else if (name === '--baseline') flags.baseline = value();
    else if (name === '--check') flags.check = true;
    else throw new Error(`unknown argument ${argv[i]}; usage: node tools/interface.mjs --root <plugin dir> [--baseline <file>] [--check]`);
  }
  if (!flags.root) throw new Error('--root <plugin dir> is required');
  return flags;
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

