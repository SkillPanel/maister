/** Everything but the version, read from the tree at `root`. */
export async function describe(root) {
  const load = relative => import(pathToFileURL(path.join(root, ENGINE, relative)).href);
  const shapes = await load('lib/interface-shapes.mjs');
  const state = await load('lib/state.mjs');
  const { SUBJECT_KINDS } = await load('lib/gate-subject.mjs');
  const { verbs, runners } = verbTable(fs.readFileSync(path.join(root, ENGINE, 'workflow.mjs'), 'utf8'));
  const refusals = refusalsByVerb(path.join(root, ENGINE), verbs, runners);

  return sorted({
    gate_request: { keys: declared(shapes.GATE_REQUEST) },
    checkpoint: {
      version: shapes.CHECKPOINT_VERSION,
      kinds: Object.values(shapes.CHECKPOINT_KIND),
      subject_kinds: SUBJECT_KINDS.map(each => each.kind),
      keys: Object.fromEntries(Object.entries(shapes.CHECKPOINT_KEYS).map(([kind, shape]) => [kind, declared(shape)])),
    },
    state: {
      schema_version: state.STATE_SCHEMA_VERSION,
      patch_keys: state.PATCH_KEYS,
      top_level_blocks: state.TOP_LEVEL_BLOCKS,
      context_blocks: state.CONTEXT_BLOCKS,
      workflow_keys: state.WORKFLOW_KEYS,
      node_keys: state.NODE_KEYS,
      node_statuses: state.NODE_STATUSES,
      writer_fields: state.WRITER_FIELDS,
      clock_fields: state.CLOCK_FIELDS,
      pending_gate_keys: state.PENDING_KEYS,
      parent_keys: state.PARENT_KEYS,
    },
    engine: {
      verbs: Object.fromEntries(Object.entries(verbs).map(([verb, { flags }]) => [verb, { flags, refusals: refusals[verb] }])),
    },
    agents: names(path.join(root, 'agents'), entry => entry.isFile() && entry.name.endsWith('.md'), name => name.slice(0, -3)),
    skills: names(path.join(root, 'skills'), entry => entry.isDirectory() && fs.existsSync(path.join(root, 'skills', entry.name, 'SKILL.md'))),
    commands: names(path.join(root, 'commands'), entry => entry.isFile() && entry.name.endsWith('.md'), name => name.slice(0, -3)),
    hooks: hooksOf(root),
    mcp: mcpOf(root),
  });
}

/** A shape declaration as the file carries it: every key's type, required flag, and what it holds. */
function declared(shape) {
  return Object.fromEntries(Object.entries(shape).map(([key, spec]) => [key, declaration(spec)]));
}

function declaration(spec) {
  const out = { type: spec.type };
  if (spec.required !== undefined) out.required = spec.required;
  if (spec.values) out.values = spec.values;
  if (spec.see) out.see = spec.see;
  if (spec.keys) out.keys = declared(spec.keys);
  if (spec.items) out.items = declaration(spec.items);
  return out;
}

function names(dir, keep, name = each => each) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).filter(keep).map(entry => name(entry.name)).sort();
}

/** The events `hooks/hooks.json` registers, each with its matchers (`*` for none), and the hooks modules it names. */
function hooksOf(root) {
  const config = readJson(path.join(root, 'hooks/hooks.json')) ?? {};
  const events = {};
  for (const [event, entries] of Object.entries(config.hooks ?? {})) {
    events[event] = [...new Set((entries ?? []).map(entry => entry.matcher ?? '*'))].sort();
  }
  const modules = (config.modules ?? []).map(each => path.posix.basename(each)).sort();
  return { events, modules };
}

/** The MCP servers the tree ships, and the MCP tool names its shipped files name. */
function mcpOf(root) {
  const manifest = readJson(path.join(root, '.claude-plugin/plugin.json')) ?? {};
  const bundled = readJson(path.join(root, '.mcp.json')) ?? {};
  const servers = [...new Set([
    ...Object.keys(isMap(manifest.mcpServers) ? manifest.mcpServers : {}),
    ...Object.keys(isMap(bundled.mcpServers) ? bundled.mcpServers : {}),
  ])].sort();
  const tools = new Set();
  for (const file of shippedFiles(root)) {
    const text = fs.readFileSync(file, 'utf8');
    for (const [name] of text.matchAll(/mcp__[A-Za-z0-9-]+(?:__[A-Za-z0-9_*-]*)?/g)) tools.add(name);
    // A host's own spelling, `<server>/<tool>`, in an agent's tool allowlist.
    for (const [line] of text.matchAll(/^tools:.*$/gm)) {
      for (const [, name] of line.matchAll(/"([A-Za-z0-9_-]+\/[A-Za-z0-9_*-]+)"/g)) tools.add(name);
    }
  }
  return { servers, tools: [...tools].sort() };
}

function shippedFiles(root) {
  const found = [];
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.(?:md|mjs|json|yml)$/.test(entry.name) && full !== path.join(root, FILE)) found.push(full);
    }
  };
  walk(root);
  return found.sort();
}

const isMap = value => value !== null && typeof value === 'object' && !Array.isArray(value);

/** `value` with every map's keys in order, so the file diffs line for line between two commits. */
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted);
  if (!isMap(value)) return value;
  return Object.fromEntries(Object.keys(value).sort().map(key => [key, sorted(value[key])]));
}

